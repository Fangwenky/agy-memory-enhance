"""Hook handlers. Each takes the stdin payload and returns the stdout object."""
import json
import os
import sys
import time
import traceback

from . import brief as B
from . import config as C
from . import detect as D
from .store import Store, resolve_root

PLUGIN_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MEM_SCRIPT = os.path.join(PLUGIN_ROOT, "skills", "agy-memory", "scripts", "mem")
TAG = "[agy-memory]"


# ---------------------------------------------------------------- plumbing
def open_store(payload):
    root = resolve_root(payload)
    cfg = C.load(root)
    return Store(root, cfg["redactPatterns"]).ensure(), cfg


def shim_path(store):
    return store.path("bin", "mem")


def ensure_shim(store):
    path = shim_path(store)
    body = ("#!/bin/sh\n# generated by agy-memory; points at the installed plugin\n"
            f'exec python3 "{MEM_SCRIPT}" --root "{store.root}" "$@"\n')
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == body:
                return path
    except OSError:
        pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    os.chmod(path, 0o755)
    return path


def system_message(text):
    return {"systemMessage": {"systemMessage": text}}


def set_current(store, conv, payload):
    store.save_json({"convId": conv, "ts": time.time(),
                     "transcriptPath": payload.get("transcriptPath"),
                     "model": payload.get("modelName")}, "state", "current.json")


def model_peaks(store):
    return store.load_json("state", "models.json")


def render_brief(store, cfg, conv):
    return B.render(store.read("ledger.jsonl"), conv, cfg["briefMaxTokens"])


def budgeted(state, cfg, text, fallback):
    """Enforce the per-session injection budget (design §7.0)."""
    t = B.est_tokens(text)
    if state["injectedTokens"] + t > cfg["sessionInjectBudgetTokens"]:
        text, t = fallback, B.est_tokens(fallback)
    state["injectedTokens"] += t
    return text


# ---------------------------------------------------------------- messages
def intro_text(shim, brief):
    head = (f"{TAG} Project memory is enabled. Memory CLI: `{shim}` "
            f"(`{shim} brief`, `{shim} add <type> \"...\"`; load the `agy-memory` skill for the protocol).")
    return head + ("\n\n" + brief if brief else "")


def align_text(shim, signal, brief):
    return (f"{TAG} Context compaction detected (signal: {signal}). Earlier conversation was replaced "
            "by a summary and details may be lost or paraphrased. Before continuing, load the "
            f"`agy-memory` skill and run its alignment procedure. Memory CLI: `{shim}`.\n\n"
            + (brief or "(memory ledger is empty)"))


def nudge_text(shim, n):
    where = (f"compaction expected near ~{n['modelPeak'] // 1000}k" if n["modelPeak"]
             else "compaction threshold for this model not yet observed")
    return (f"{TAG} Context is ~{n['ctx'] // 1000}k tokens; {where}. Save current constraints, "
            f"decisions and progress now with `{shim} add ...`, then continue.")


def short_fallback(shim):
    return f"{TAG} Memory brief omitted (injection budget reached). Run `{shim} brief`."


# ---------------------------------------------------------------- handlers
def _init_session(store, cfg, conv, state, payload):
    shim = ensure_shim(store)
    brief = render_brief(store, cfg, conv)
    text = budgeted(state, cfg, intro_text(shim, brief), short_fallback(shim))
    state["initialized"] = True
    state["model"] = payload.get("modelName")
    store.append("events.jsonl", store.event(conv, "intro", {"tokens": B.est_tokens(text)}))
    return [system_message(text)]


def session_start(payload):
    store, cfg = open_store(payload)
    conv = payload.get("conversationId") or "unknown"
    state = {**D.fresh_state(), **store.conv_state(conv)}
    set_current(store, conv, payload)
    out = []
    if not state["initialized"]:
        out = _init_session(store, cfg, conv, state, payload)
    store.save_conv_state(conv, state)
    return {"injectSteps": out} if out else {}


def pre_invocation(payload):
    store, cfg = open_store(payload)
    conv = payload.get("conversationId") or "unknown"
    state = {**D.fresh_state(), **store.conv_state(conv)}
    set_current(store, conv, payload)
    model = payload.get("modelName") or state.get("model")
    first = not state["initialized"]

    from . import transcript as T
    steps, state["offset"], reset = T.read_new(payload.get("transcriptPath"), state["offset"])
    events, peaks = D.scan(state, steps, cfg, conv)
    if reset:
        events.append(("transcript_reset", None, {}))

    peaks_by_model = model_peaks(store)
    for p in peaks:
        if p and model:
            peaks_by_model[model] = p
    if peaks:
        store.save_json(peaks_by_model, "state", "models.json")

    store.append_many("events.jsonl", [store.event(conv, k, d, i) for k, i, d in events])
    D.observe_ledger(state, store.size("ledger.jsonl"))

    inject = []
    if first:
        # resumed/new session: the intro brief doubles as alignment; historic
        # compactions found while catching up do not need a separate signal
        state["pendingAlign"] = None
        inject = _init_session(store, cfg, conv, state, payload)
    elif state["pendingAlign"]:
        shim = ensure_shim(store)
        text = budgeted(state, cfg,
                        align_text(shim, state["pendingAlign"], render_brief(store, cfg, conv)),
                        f"{TAG} Context compaction detected. Load the `agy-memory` skill and run "
                        f"alignment; brief: `{shim} brief`.")
        store.append("events.jsonl", store.event(conv, "align_nudge",
                                                 {"signal": state["pendingAlign"]}))
        state["pendingAlign"] = None
        inject = [system_message(text)]
    else:
        n = D.should_nudge(state, cfg, peaks_by_model.get(model))
        if n:
            shim = shim_path(store)
            text = nudge_text(shim, n)
            state["injectedTokens"] += B.est_tokens(text)
            store.append("events.jsonl", store.event(conv, "checkpoint_nudge", n))
            inject = [system_message(text)]

    state["model"] = model
    store.save_conv_state(conv, state)
    return {"injectSteps": inject} if inject else {}


_PATH_KEYS = ("Path", "TargetFile", "AbsolutePath", "path", "file_path")


def post_tool_use(payload):
    store, cfg = open_store(payload)
    conv = payload.get("conversationId") or "unknown"
    call = payload.get("toolCall") or {}
    name, args = call.get("name") or "", call.get("args") or {}
    err = payload.get("error") or None
    if name in cfg["editToolNames"]:
        path = next((args[k] for k in _PATH_KEYS if isinstance(args.get(k), str)), None)
        store.append("events.jsonl", store.event(conv, "file_edit",
                                                 {"path": path, "tool": name, "error": err},
                                                 payload.get("stepIdx")))
    elif name == "run_command":
        store.append("events.jsonl", store.event(conv, "command",
                                                 {"cmd": args.get("CommandLine"), "error": err},
                                                 payload.get("stepIdx")))
    return {}


# ---------------------------------------------------------------- entrypoint
HANDLERS = {
    "SessionStart": session_start,
    "PreInvocation": pre_invocation,
    "PostToolUse": post_tool_use,
}


def main(event):
    """Never break the agent: any failure logs and returns {}."""
    raw = sys.stdin.read()
    try:
        payload = json.loads(raw) if raw.strip() else {}
        out = HANDLERS[event](payload)
    except Exception:  # noqa: BLE001
        _log_error(event, raw)
        out = {}
    sys.stdout.write(json.dumps(out, ensure_ascii=False))


def _log_error(event, raw):
    try:
        d = os.path.expanduser("~/.agy-memory")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "hook-errors.log"), "a", encoding="utf-8") as f:
            f.write(f"--- {time.ctime()} {event}\n{traceback.format_exc()}\n")
    except Exception:  # noqa: BLE001
        pass
